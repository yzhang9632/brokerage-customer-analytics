# -*- coding: utf-8 -*-
"""Business Overview: KPIs + monthly turnover trend (Q7) + customer asset tiers (Q6)."""
import plotly.express as px
import streamlit as st

from db import query

st.set_page_config(page_title="Retail Brokerage Customer Analytics Platform", page_icon="📈", layout="wide")
st.title("📈 Retail Brokerage Customer Analytics Platform")
st.caption("Data: Real CSI 300 market quotes (AKShare) + synthetic transaction records generated by a behavioral model (~970,000 trades) · PostgreSQL")

kpi = query("""
SELECT (SELECT COUNT(*) FROM customer) AS customers,
       (SELECT ROUND(SUM(total_asset)/1e8, 2) FROM asset_snapshot
         WHERE month=(SELECT MAX(month) FROM asset_snapshot)) AS asset_yi,
       (SELECT ROUND(SUM(amount)/1e8, 2) FROM trade
         WHERE month=(SELECT MAX(month) FROM trade)) AS month_turnover_yi,
       (SELECT COUNT(DISTINCT account_id) FROM trade
         WHERE month=(SELECT MAX(month) FROM trade)) AS active_accounts
""").iloc[0]
c1, c2, c3, c4 = st.columns(4)
c1.metric("Retail Customers", f"{int(kpi.customers):,}")
c2.metric("Total Customer Assets", f"¥{kpi.asset_yi * 100:,.2f}M")
c3.metric("Monthly Turnover", f"¥{kpi.month_turnover_yi * 100:,.2f}M")
c4.metric("Active Accounts This Month", f"{int(kpi.active_accounts):,}")

left, right = st.columns([3, 2])
with left:
    st.subheader("Market-wide Monthly Turnover (Q7: MoM)")
    df = query("""
        WITH m AS (SELECT month, SUM(amount) AS turnover FROM trade GROUP BY month)
        SELECT month, ROUND(turnover/1e8, 2) AS turnover_yi,
               ROUND(100.0*(turnover - LAG(turnover) OVER (ORDER BY month))
                     / LAG(turnover) OVER (ORDER BY month), 2) AS mom_pct
        FROM m ORDER BY month
    """)
    fig = px.line(df, x="month", y="turnover_yi", markers=True,
                  labels={"month": "Month", "turnover_yi": "Turnover (CNY 100M)"})
    st.plotly_chart(fig, use_container_width=True)
    st.dataframe(df, use_container_width=True, hide_index=True)

with right:
    st.subheader("Customer Asset Quintiles (Q6)")
    tier = query("""
        WITH latest AS (SELECT account_id, total_asset FROM asset_snapshot
                        WHERE month=(SELECT MAX(month) FROM asset_snapshot)),
        ranked AS (SELECT *, NTILE(5) OVER (ORDER BY total_asset DESC) AS tier FROM latest)
        SELECT 'Tier ' || tier AS tier_name, COUNT(*) AS customers,
               ROUND(SUM(total_asset)/1e8, 2) AS asset_yi
        FROM ranked GROUP BY tier ORDER BY tier
    """)
    fig2 = px.bar(tier, x="tier_name", y="asset_yi", text="customers",
                  labels={"tier_name": "Asset Tier (1 = Top)", "asset_yi": "Assets (CNY 100M)"})
    st.plotly_chart(fig2, use_container_width=True)
    st.dataframe(tier, use_container_width=True, hide_index=True)
